export function iconRows(id: IconId): string[] {
  return P[MAP[id]];
}

/** Returns a canvas with the icon drawn at `scale` pixels per cell. */
export function iconCanvas(id: IconId, color: string, scale = 1): HTMLCanvasElement {
  const rows = iconRows(id);
  const c = makeCanvas(9 * scale, 9 * scale);
  const g = c.getContext('2d')!;
  g.fillStyle = color;
  for (let y = 0; y < 9; y++) for (let x = 0; x < 9; x++) if (rows[y][x] === '#') g.fillRect(x * scale, y * scale, scale, scale);
  return c;
}
